/**
 * Index Updater Tests
 */

import path from 'path';
import fs from 'fs-extra';
import IndexUpdater from '../src/updater';
import DocumentScanner from '../src/scanner';
import { createTestConfig, createTempTestDir, TEMP_DIR } from './setup';

describe('IndexUpdater', () => {
  let updater: IndexUpdater;
  let scanner: DocumentScanner;
  let testDir: string;

  beforeEach(async () => {
    testDir = await createTempTestDir('updater-test');
    const config = createTestConfig(testDir);
    config.docsDir = path.join(TEMP_DIR, 'docs');
    config.indexPath = path.join(TEMP_DIR, 'docs', 'PROJECT_INDEX.md');
    updater = new IndexUpdater(config);
    scanner = new DocumentScanner(config);
  });

  describe('updateIndex', () => {
    it('should create a new index file', async () => {
      // Remove existing index
      const indexPath = path.join(TEMP_DIR, 'docs', 'PROJECT_INDEX.md');
      await fs.remove(indexPath);
      
      const documents = await scanner.scanDocuments({ verbose: false });
      await updater.updateIndex(documents, { backup: false });
      
      expect(await fs.pathExists(indexPath)).toBe(true);
      
      const content = await fs.readFile(indexPath, 'utf-8');
      expect(content).toContain('# ');
      expect(content).toContain('Documentation Index');
      expect(content).toContain('System Architecture');
    });

    it('should update existing index while preserving structure', async () => {
      const documents = await scanner.scanDocuments();
      await updater.updateIndex(documents, { backup: false });
      
      const indexPath = path.join(TEMP_DIR, 'docs', 'PROJECT_INDEX.md');
      const content = await fs.readFile(indexPath, 'utf-8');
      
      // Should contain documents from different categories
      expect(content).toContain('🏗️ Technical Documentation');
      expect(content).toContain('📚 API Documentation');
      expect(content).toContain('System Architecture');
      expect(content).toContain('REST API Documentation');
    });

    it('should create backup when requested', async () => {
      const documents = await scanner.scanDocuments();
      await updater.updateIndex(documents, { backup: true });
      
      const indexDir = path.dirname(path.join(TEMP_DIR, 'docs', 'PROJECT_INDEX.md'));
      const files = await fs.readdir(indexDir);
      const backups = files.filter(file => file.includes('PROJECT_INDEX.md.backup'));
      
      expect(backups.length).toBeGreaterThan(0);
    });

    it('should perform dry run without making changes', async () => {
      const indexPath = path.join(TEMP_DIR, 'docs', 'PROJECT_INDEX.md');
      const originalContent = await fs.readFile(indexPath, 'utf-8');
      
      const documents = await scanner.scanDocuments();
      await updater.updateIndex(documents, { dryRun: true, backup: false });
      
      const newContent = await fs.readFile(indexPath, 'utf-8');
      expect(newContent).toBe(originalContent);
    });

    it('should organize documents by category', async () => {
      const documents = await scanner.scanDocuments();
      await updater.updateIndex(documents);
      
      const indexPath = path.join(TEMP_DIR, 'docs', 'PROJECT_INDEX.md');
      const content = await fs.readFile(indexPath, 'utf-8');
      
      // Check category order and structure
      const technicalPos = content.indexOf('🏗️ Technical Documentation');
      const apiPos = content.indexOf('📚 API Documentation');
      const userPos = content.indexOf('👥 User Documentation');
      
      // Technical should come before API which should come before User
      expect(technicalPos).toBeGreaterThan(-1);
      expect(apiPos).toBeGreaterThan(technicalPos);
      expect(userPos).toBeGreaterThan(apiPos);
    });

    it('should include documentation metadata', async () => {
      const documents = await scanner.scanDocuments();
      await updater.updateIndex(documents);
      
      const indexPath = path.join(TEMP_DIR, 'docs', 'PROJECT_INDEX.md');
      const content = await fs.readFile(indexPath, 'utf-8');
      
      expect(content).toContain('Total Documents:');
      expect(content).toContain('Last Updated:');
      expect(content).toContain('Generated by: CIV Documentation Tracker');
    });
  });
});